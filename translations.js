  /* Internal status -> simplified customer step (0 received, 1 in progress, 2 delivered, -1 cancelled) */
  var STATUS_MAP = {
    pending: 0, confirmed: 1, processing: 1,
    shipped: 1, out_for_delivery: 1,
    delivered: 2, cancelled: -1
  };

  var lang = 'en';
  try {
    var saved = localStorage.getItem('blush_lang');
    if (saved === 'ar' || saved === 'en') lang = saved;
  } catch (e) { /* storage unavailable */ }

  function t(key, params) {
    var d = DICT[lang] || DICT.en;
    var s = (key in d) ? d[key] : DICT.en[key];
    if (s === undefined) return key;
    if (params) {
      Object.keys(params).forEach(function (k) {
        s = s.split('{' + k + '}').join(params[k]);
      });
    }
    return s;
  }

  function apply(root) {
    var scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
  }

  function setLang(l) {
    if (l !== 'en' && l !== 'ar') l = 'en';
    lang = l;
    try { localStorage.setItem('blush_lang', l); } catch (e) { /* ignore */ }
    document.documentElement.lang = l;
    document.documentElement.dir = (l === 'ar') ? 'rtl' : 'ltr';
    document.documentElement.classList.toggle('lang-ar', l === 'ar');
    apply();
    document.dispatchEvent(new CustomEvent('lang:change', { detail: { lang: l } }));
  }

  /* Currency: EGP, Latin digits in both languages (common in Egyptian e-commerce). */
  function fmtMoney(n) {
    var num = Number(n) || 0;
    var s = new Intl.NumberFormat('en-US', {
      minimumFractionDigits: 0,
      maximumFractionDigits: 2
    }).format(num);
    return (lang === 'ar') ? s + ' \u062c.\u0645' : 'EGP ' + s;
  }

  function fmtDate(iso) {
    if (!iso) return '';
    var d = new Date(iso);
    if (isNaN(d.getTime())) return '';
    return d.toLocaleDateString(lang === 'ar' ? 'ar-EG' : 'en-GB', {
      day: 'numeric', month: 'long', year: 'numeric'
    });
  }

  function fmtDateTime(iso) {
    if (!iso) return '';
    var d = new Date(iso);
    if (isNaN(d.getTime())) return '';
    return d.toLocaleDateString(lang === 'ar' ? 'ar-EG' : 'en-GB', {
      day: 'numeric', month: 'short', year: 'numeric'
    }) + ' \u00b7 ' + d.toLocaleTimeString(lang === 'ar' ? 'ar-EG' : 'en-GB', {
      hour: '2-digit', minute: '2-digit'
    });
  }

  function govLabel(value) {
    for (var i = 0; i < GOVS.length; i++) {
      if (GOVS[i][0] === value) return lang === 'ar' ? GOVS[i][1] : GOVS[i][0];
    }
    return value || '';
  }

  function statusKey(status) {
    var map = {
      pending: 'st_pending', confirmed: 'st_confirmed', processing: 'st_processing',
      shipped: 'st_shipped', out_for_delivery: 'st_out', delivered: 'st_delivered',
      cancelled: 'st_cancelled'
    };
    return map[status] || status;
  }

  function payKey(status) {
    var map = { unpaid: 'pay_unpaid', paid: 'pay_paid', failed: 'pay_failed', refunded: 'pay_refunded', partial: 'pay_partial' };
    return map[status] || status;
  }

  /* Boot: apply saved language immediately */
  document.documentElement.lang = lang;
  document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';
  document.documentElement.classList.toggle('lang-ar', lang === 'ar');

  window.I18N = {
    t: t,
    apply: apply,
    setLang: setLang,
    get lang() { return lang; },
    isRTL: function () { return lang === 'ar'; },
    fmtMoney: fmtMoney,
    fmtDate: fmtDate,
    fmtDateTime: fmtDateTime,
    govLabel: govLabel,
    GOVS: GOVS,
    STATUS_MAP: STATUS_MAP,
    statusKey: statusKey,
    payKey: payKey
  };
